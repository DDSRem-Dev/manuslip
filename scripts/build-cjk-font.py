"""Prepare the pinned offline font; requires FontTools 4.64.0 and Brotli 1.2.0."""

import argparse
import hashlib
import json
from pathlib import Path
import unicodedata

from fontTools import subset
from fontTools.ttLib import TTFont


SOURCE_SHA256 = '990c807e79c25662a5a9ecf7f971baeb2bf2eab9a559e5ecf15cdfdb8561d21f'
SOURCE_URL = (
    'https://raw.githubusercontent.com/notofonts/noto-cjk/'
    '523d033d6cb47f4a80c58a35753646f5c3608a78/'
    'Sans/Variable/TTF/NotoSansCJKsc-VF.ttf'
)
CJK_RANGES = [
    (0x1100, 0x11FF), (0x2E80, 0x9FFF), (0xA960, 0xA97F),
    (0xAC00, 0xD7FF), (0xF900, 0xFAFF), (0xFE10, 0xFE1F),
    (0xFE30, 0xFE4F), (0xFF00, 0xFFEF), (0x16FE0, 0x18D8F),
    (0x1AFF0, 0x1B16F), (0x20000, 0x323AF),
]


def unicode_ranges(points):
    spans = []
    for point in sorted(points):
        if spans and spans[-1][1] + 1 == point:
            spans[-1][1] = point
        else:
            spans.append([point, point])
    return ', '.join(
        f'U+{first:X}' if first == last else f'U+{first:X}-{last:X}'
        for first, last in spans
    )


def variations(font, glyph_ids=False):
    return {
        selector: [
            (point, font.getGlyphID(glyph) if glyph_ids and glyph is not None else glyph)
            for point, glyph in entries
        ]
        for table in font['cmap'].tables if table.format == 14
        for selector, entries in table.uvsDict.items()
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    source = args.source.read_bytes()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError('Expected the pinned Noto Sans CJK SC 2.004 source')
    args.output_dir.mkdir(parents=True, exist_ok=False)
    original = TTFont(args.source, recalcTimestamp=False)
    cmap = original.getBestCmap()
    uvs = variations(original)
    groups = {}
    for point, glyph in cmap.items():
        groups.setdefault(glyph, []).append(point)

    # A glyph shared by 文 and the Kangxi radical ⽂ makes Chromium's PDF
    # reverse cmap ambiguous. Each face gets at most one code point per glyph.
    # Ordinary, normalized characters stay in the main face. Separate faces
    # preserve every alias, all variable weights and their OpenType closures.
    layers = []
    for points in groups.values():
        ordered = sorted(points, key=lambda point: (
            unicodedata.normalize('NFKC', chr(point)) != chr(point), point,
        ))
        for index, point in enumerate(ordered):
            if index == len(layers):
                layers.append({})
            layers[index][point] = cmap[point]

    files = []
    styles = ['/* Generated by scripts/build-cjk-font.py. Latin faces remain unchanged. */']
    union = {}
    for index, layer in enumerate(layers):
        options = subset.Options()
        options.layout_features = ['*']
        options.layout_scripts = ['*']
        options.name_IDs = ['*']
        options.name_languages = ['*']
        options.name_legacy = True
        options.glyph_names = True
        options.notdef_glyph = True
        options.notdef_outline = True
        font = TTFont(args.source, recalcTimestamp=False)
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=[*layer, *uvs])
        subsetter.subset(font)
        assert font.getBestCmap() == layer
        assert len(set(layer.values())) == len(layer)
        expected_uvs = {
            selector: [(point, glyph) for point, glyph in entries if point in layer]
            for selector, entries in uvs.items()
            if any(point in layer for point, _glyph in entries)
        }
        assert variations(font) == expected_uvs
        filename = 'noto-sans-cjk-sc' + (f'-aliases-{index}' if index else '') + '.woff2'
        font.flavor = 'woff2'
        path = args.output_dir / filename
        expected_ids = {point: font.getGlyphID(glyph) for point, glyph in layer.items()}
        expected_variations = variations(font, glyph_ids=True)
        font.save(path)
        saved = TTFont(path)
        # The source post table has no glyph names. Reopening synthesizes names
        # from the new cmap, so compare stable glyph IDs rather than those names.
        assert {point: saved.getGlyphID(glyph) for point, glyph in saved.getBestCmap().items()} == expected_ids
        assert variations(saved, glyph_ids=True) == expected_variations
        assert [(axis.axisTag, axis.minValue, axis.maxValue) for axis in saved['fvar'].axes] == [
            ('wght', 100, 900),
        ]
        union.update(layer)
        body = path.read_bytes()
        files.append({
            'name': filename, 'bytes': len(body),
            'sha256': hashlib.sha256(body).hexdigest(),
            'codepoints': len(layer), 'glyphs': len(saved.getGlyphOrder()),
        })
        selected = [point for point in layer if any(first <= point <= last for first, last in CJK_RANGES)]
        # The main face's effective range also intersects its cmap. Alias faces
        # have disjoint explicit ranges and occur after it in the CSS cascade.
        ranges = unicode_ranges(selected) if index else ', '.join(
            f'U+{first:X}-{last:X}' for first, last in CJK_RANGES
        )
        styles.append(
            '@font-face {\n  font-family: "Manuslip CJK";\n'
            f'  src: url("/assets/{filename}") format("woff2");\n'
            '  font-style: normal;\n  font-weight: 100 900;\n  font-display: swap;\n'
            f'  unicode-range: {ranges};\n}}'
        )
        print(json.dumps(files[-1]), flush=True)
    assert union == cmap
    (args.output_dir / 'fonts.css').write_text('\n'.join(styles) + '\n', encoding='utf-8')
    manifest = {
        'source': SOURCE_URL, 'sourceSha256': SOURCE_SHA256,
        'codepoints': len(cmap), 'sourceGlyphs': len(original.getGlyphOrder()),
        'weight': [100, 900], 'files': files,
    }
    (args.output_dir / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'status': 'verified', 'codepoints': len(union), 'faces': len(files)}), flush=True)


if __name__ == '__main__':
    main()
